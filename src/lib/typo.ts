/**
 * Русская типографика: неразрывные пробелы.
 *
 * Аудит переносов на главной показывал строки вида «Три шага, и» —
 * одинокий союз в конце строки. По правилам набора однобуквенные и
 * двухбуквенные слова (предлоги, союзы, частицы) не отрываются от
 * следующего слова, а числа — от своей единицы измерения.
 *
 * Делается на этапе рендера, а не руками в строках: неразрывный
 * пробел, вбитый в исходник, невидим при чтении кода и теряется при
 * любой правке текста.
 */
const SHORT = /(^|[\s(«"])([а-яёa-z]{1,2})\s+/gi;
/** Число и то, что за ним: «19 стран», «75 Гбит/с», «199 ₽». */
const NUMERIC = /(\d)\s+([а-яёa-z₽%]+)/gi;
/** Тире не должно начинать строку — привязываем к предыдущему слову. */
const DASH = /\s+([—–])\s/g;

export function typo(text: string): string {
  return text
    .replace(SHORT, (_, pre, word) => `${pre}${word} `)
    .replace(NUMERIC, (_, digit, word) => `${digit} ${word}`)
    .replace(DASH, " $1 ");
}
