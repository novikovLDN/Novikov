/** Шаг сетки в градусах. */
export const CELL_DEG = 3;
/** Широта центра верхнего ряда и долгота центра левой колонки. */
export const LAT_TOP = 73.5;
export const LON_LEFT = -178.5;

export const COLS = WORLD_ROWS[0].length;
export const ROWS = WORLD_ROWS.length;

/** Сторона ячейки в координатах холста. */
export const CELL = 7;
export const MAP_W = COLS * CELL;
export const MAP_H = ROWS * CELL;

/** Географические координаты → точка холста. */
export function project(lat: number, lon: number): { x: number; y: number } {
  const col = (lon - LON_LEFT) / CELL_DEG;
  const row = (LAT_TOP - lat) / CELL_DEG;
  return { x: (col + 0.5) * CELL, y: (row + 0.5) * CELL };
}

/**
 * Точки суши одним SVG-путём.
 *
 * Тысяча семьсот отдельных <circle> — это тысяча семьсот узлов DOM на
 * странице, которая продаёт скорость. Один путь из квадратов рисуется
 * тем же браузерным примитивом, что и любая иконка.
 */
export function landPath(dot = 4): string {
  return buildPath(() => true, dot);
}

/**
 * Две дорожки суши: обычная и «горячая» — ячейки вокруг наших точек
 * присутствия. Страна, где мы стоим, светится сама, а не только несёт
 * маркер: карта читается как охват, а не как россыпь булавок.
 */
export function landPaths(
  spots: Array<{ lat: number; lon: number }>,
  radiusCells = 1.9,
  dot = 4
): { base: string; hot: string } {
  const centres = spots.map((s) => ({
    c: (s.lon - LON_LEFT) / CELL_DEG,
    r: (LAT_TOP - s.lat) / CELL_DEG,
  }));
  const isHot = (c: number, r: number) =>
    centres.some((p) => Math.hypot(p.c - c, p.r - r) <= radiusCells);

  return {
    base: buildPath((c, r) => !isHot(c, r), dot),
    hot: buildPath((c, r) => isHot(c, r), dot),
  };
}

function buildPath(keep: (col: number, row: number) => boolean, dot: number): string {
  const parts: string[] = [];
  for (let r = 0; r < ROWS; r++) {
    for (let c = 0; c < COLS; c++) {
      if (WORLD_ROWS[r][c] !== "#") continue;
      if (!keep(c, r)) continue;
      const x = (c + 0.5) * CELL - dot / 2;
      const y = (r + 0.5) * CELL - dot / 2;
      parts.push(`M${x.toFixed(1)} ${y.toFixed(1)}h${dot}v${dot}h-${dot}z`);
    }
  }
  return parts.join("");
}

/** Прямоугольник карты в градусах — область для врезки. */
export interface Bounds {
  lonMin: number;
  lonMax: number;
  latMin: number;
  latMax: number;
}

/** Вся карта. */
export const WORLD_BOUNDS: Bounds = {
  lonMin: LON_LEFT - CELL_DEG / 2,
  lonMax: LON_LEFT + COLS * CELL_DEG,
  latMin: LAT_TOP - ROWS * CELL_DEG,
  latMax: LAT_TOP + CELL_DEG / 2,
};

/**
 * Европа крупным планом.
 *
 * Восемь наших стран умещаются в кадр шириной сорок пять градусов: на
 * мировой карте их маркеры перекрывают друг друга, и попасть курсором
 * в нужную страну невозможно. Врезка — не украшение, а единственное
 * место, где европейские точки кликабельны.
 */
export const EUROPE_BOUNDS: Bounds = { lonMin: -12, lonMax: 36, latMin: 33, latMax: 63 };

/** viewBox холста для области. */
export function viewBox(b: Bounds): string {
  const tl = project(b.latMax, b.lonMin);
  const br = project(b.latMin, b.lonMax);
  return `${tl.x.toFixed(1)} ${tl.y.toFixed(1)} ${(br.x - tl.x).toFixed(1)} ${(br.y - tl.y).toFixed(1)}`;
}

/** Доля точки внутри области — для позиционирования маркеров в HTML. */
export function positionIn(b: Bounds, lat: number, lon: number): { xPct: number; yPct: number } {
  const tl = project(b.latMax, b.lonMin);
  const br = project(b.latMin, b.lonMax);
  const p = project(lat, lon);
  return {
    xPct: ((p.x - tl.x) / (br.x - tl.x)) * 100,
    yPct: ((p.y - tl.y) / (br.y - tl.y)) * 100,
  };
}

export function within(b: Bounds, lat: number, lon: number): boolean {
  return lat >= b.latMin && lat <= b.latMax && lon >= b.lonMin && lon <= b.lonMax;
}

/** Пропорции области — чтобы холст не подгонялся числами руками. */
export function aspect(b: Bounds): number {
  const tl = project(b.latMax, b.lonMin);
  const br = project(b.latMin, b.lonMax);
  return (br.x - tl.x) / (br.y - tl.y);
}
