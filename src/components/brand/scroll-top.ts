/**
 * Одна точка возврата к началу страницы.
 *
 * На страницах бренда прокруткой управляет Lenis: он держит
 * собственную позицию и на следующем же кадре возвращает страницу
 * туда, где считает нужным. Нативный `window.scrollTo` там не
 * работает — проверено: после нажатия scrollY оставался прежним.
 *
 * Поэтому Lenis, поднявшись, регистрирует здесь свой способ
 * перемещения, а кнопка спрашивает у этого модуля. Модуль намеренно
 * крошечный и ни от чего не зависит: кнопка стоит в корневой
 * разметке, и импорт из motion.tsx затянул бы gsap со всеми
 * плагинами на каждую страницу сайта — ровно то, от чего этот слой
 * недавно отвязали.
 */
type Scroller = (y: number) => void;

let scroller: Scroller | null = null;

/** Вызывает Lenis при подъёме и передаёт null при остановке. */
export function registerScroller(fn: Scroller | null) {
  scroller = fn;
}

/**
 * Возврат мгновенный, а не плавный. `html` объявляет
 * `scroll-behavior: smooth`, и плавная прокрутка отсюда шла бы через
 * все закреплённые сцены — каждая отматывала бы свою анимацию задом
 * наперёд, и возврат занимал бы секунды.
 *
 * Значение "instant", а не "auto": по спецификации `auto` означает
 * «взять поведение из CSS», то есть на этом сайте — плавно, и
 * возврат становился гонкой с уже идущей анимацией прокрутки
 * (в замерах он то срабатывал, то нет). `instant` не оставляет
 * выбора.
 */
export function scrollToTop() {
  if (scroller) {
    scroller(0);
    return;
  }
  window.scrollTo({ top: 0, left: 0, behavior: "instant" });
}
