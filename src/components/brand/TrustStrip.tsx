/**
 * Полоса доверия.
 *
 * Практика конверсии 2026: короткие явные утверждения о данных и об
 * условиях снимают неуверенность быстрее любого раздела «о
 * безопасности», и работают они не в одном месте, а вдоль всего пути
 * — у первого экрана, у цены, у финального призыва. Доверие
 * накапливается, а не сообщается однажды.
 *
 * Каждая строка — проверяемое утверждение о продукте, а не лозунг.
 * Сертификаций, наград и числа пользователей здесь нет намеренно: всё
 * это требует подтверждения (COMPLIANCE-CHECK.md), а непроверяемый
 * значок доверия работает ровно наоборот.
 */
const CLAIMS = [
  "Историю подключений не храним",
  "Данные не продаём и не передаём",
  "Отмена в один клик",
  "Оплата через авторизованного оператора",
];

export default function TrustStrip({ tone = "ink" }: { tone?: "ink" | "paper" }) {
  return (
    <ul className={`b-trust b-trust-${tone}`}>
      {CLAIMS.map((c) => (
        <li key={c}>
          <span className="b-trust-tick" aria-hidden />
          {c}
        </li>
      ))}
    </ul>
  );
}
