"use client";

import { usePrefersReducedMotion } from "./motion";

/**
 * ТРАФИК — поток пакетов вдоль края страницы.
 *
 * Тонкая линия у левого края, по которой непрерывно идут маленькие
 * квадраты — от устройства к узлу и обратно. Это ambient-слой в
 * точном смысле: медленная деталь, которая держит атмосферу и не
 * забирает внимание.
 *
 * Почему именно пакеты: сайт продаёт соединение, и линия с трафиком —
 * буквальное изображение того, что происходит, когда продукт включён.
 * Абстрактные частицы значили бы то же самое, что и на любом другом
 * сайте, то есть ничего.
 *
 * Скорость подключена к общему полю движения (--b-vel): при
 * прокрутке поток ускоряется, в покое возвращается к своему ходу.
 * Собственного скрипта у слоя нет вовсе — только CSS.
 */
export default function PacketRail() {
  const reduced = usePrefersReducedMotion();
  if (reduced) return null;

  return (
    <div className="b-rail-flow" aria-hidden>
      <span className="b-rail-line" />
      {Array.from({ length: 7 }, (_, i) => (
        <span key={i} className="b-packet" style={{ ["--i" as string]: i }} />
      ))}
    </div>
  );
}
