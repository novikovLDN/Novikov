import { Sofia_Sans, Sofia_Sans_Condensed } from "next/font/google";

/**
 * Суперсемейство на весь сайт: Sofia Sans в двух ширинах.
 *
 * ЧТО БЫЛО И ПОЧЕМУ УШЛО. Golos Text — спокойный текстовый гротеск,
 * и он честно работал в системе «Гратикул», где характер держали
 * сетка и числа. Редакционный корпус устроен иначе: характер держит
 * набор, и нейтральная текстовая гарнитура в кегле 250px читается
 * никак — крупно, но безлико.
 *
 * ПОЧЕМУ ИМЕННО SOFIA SANS. Отобрано замером, а не по памяти: из
 * каталога Google Fonts взяты все вариативные гротески с кириллицей
 * (70 семейств), и у Sofia Sans единственная в списке ось веса
 * 1–1000 при живых узких начертаниях того же рисунка. Это
 * суперсемейство, а не две случайные гарнитуры: дисплей и текст
 * нарисованы одной рукой, поэтому пара не спорит, но узкое и
 * нормальное различаются с одного взгляда. Кириллица родная
 * (Lettersoup рисовали латиницу, кириллицу и греческий вместе).
 *
 * КАК РАСПРЕДЕЛЕНО. Узкое — только дисплейный слой: первый экран,
 * заголовки сцен, сумма, финальный призыв. Узкая ширина здесь не
 * приём, а условие: в нормальной ширине строка «УСКОРИТЕЛЬ» в кегле
 * 260px не встаёт в колонку 1376px, и заголовок пришлось бы
 * уменьшать. Нормальное — весь остальной текст.
 *
 * ВЕС НЕ ПЕРЕЧИСЛЯЕТСЯ СПИСКОМ. Со списком next/font выкачивает по
 * статическому файлу на каждое начертание; без него приезжает один
 * вариативный файл с непрерывной осью — той самой, к которой
 * привязан вес заголовка при прокрутке.
 */
export const brand = Sofia_Sans({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-brand",
});

export const displayFace = Sofia_Sans_Condensed({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-display",
});

/* Прежние имена оставлены псевдонимами: на них ссылаются brand.css и
   globals.css, и переписывать сотни правил ради переименования
   переменной незачем. Моноширинной в системе по-прежнему нет. */
export const display = displayFace;
export const text = brand;
export const mono = brand;
