import { Golos_Text } from "next/font/google";

/**
 * Одна гарнитура на весь сайт.
 *
 * ЧТО БЫЛО. Три семейства: Oswald (дисплей), Onest (текст), JetBrains
 * Mono (служебные метки). На первом экране они стоили 196 КБ — самая
 * крупная статья веса страницы, крупнее всего нашего JavaScript.
 *
 * ПОЧЕМУ ОДНА. Дизайн-система «Гратикул» (docs/03_DESIGN_SYSTEM.md)
 * строится на числах и на размеченной сетке, а не на контрасте
 * гарнитур. Разницу между заголовком, текстом и подписью держат кегль,
 * вес и разрядка — вариативная ось это позволяет. Моноширинная убрана
 * отдельным решением: ТЗ (6.2) запрещает «шрифт для техничности», и
 * всё, ради чего она стояла — выравнивание чисел, — делает
 * font-variant-numeric: tabular-nums.
 *
 * ПОЧЕМУ ИМЕННО GOLOS TEXT. Кириллица родная, а не дорисованная к
 * латинице (Paratype рисовали её первой). Вариативная ось веса
 * 400–900. Свободная лицензия — работает сегодня, без бюджета.
 * Характер спокойный: у Oswald узкое очко и афишная плотность, он
 * читался как объявление, а не как институция.
 *
 * Платная альтернатива на случай бюджета — Suisse Int'l или Graphik
 * (docs/QUESTIONS.md №16). Замена сводится к правке этого файла:
 * дальше по коду гарнитура известна одной переменной.
 *
 * ВЕС НЕ ПЕРЕЧИСЛЯЕТСЯ СПИСКОМ. Со списком next/font выкачивает по
 * статическому файлу на каждое начертание; без него приезжает один
 * вариативный файл с непрерывной осью — той самой, к которой
 * привязан вес заголовка при прокрутке.
 */
export const brand = Golos_Text({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-brand",
});

/* Прежние имена оставлены псевдонимами: на них ссылаются brand.css и
   globals.css, и переписывать сотни правил ради переименования
   переменной незачем. Все три указывают на одну гарнитуру. */
export const display = brand;
export const text = brand;
export const mono = brand;
