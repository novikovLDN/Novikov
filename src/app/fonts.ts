import { Oswald, Onest, JetBrains_Mono } from "next/font/google";

/**
 * Гарнитуры бренда 2027. Обоснование выбора — TRENDS.md §5.
 *
 * Кириллица отрезала половину референсов: кинетическая типографика
 * 2026 года едет на Neue Machina и Clash Grotesk, и ни у той, ни у
 * другой кириллицы нет. Из бесплатного вариативного дисплея с
 * настоящей кириллицей остались Unbounded, Onest и Manrope.
 *
 * Оба шрифта берутся вариативными файлами: вес привязывается к
 * прокрутке и к наведению, а это невозможно на наборе статических
 * начертаний.
 *
 * Inter, Roboto, Arial, Open Sans и system-ui в дисплее запрещены
 * явно — это визитная карточка сайта, собранного по умолчанию.
 */
/* Вес НЕ перечисляется списком намеренно. Со списком next/font
   выкачивает по статическому файлу на каждое начертание — тринадцать
   файлов на две гарнитуры, и это стоило 4,4 с LCP на мобильном
   профиле. Без списка приезжает один вариативный файл на семейство,
   с непрерывной осью веса — той самой, к которой привязана прокрутка
   заголовка. */
/**
 * Дисплей — сжатый гротеск вместо прежнего широкого.
 *
 * Unbounded давал плакатность, но не давал дерзости: широкое очко
 * читается спокойно и дорого. Направление сменилось на цифропанк
 * (TRENDS-2.md §3 D), а его заголовок — надпись на стене: узкая,
 * плотная, капсом. Oswald вариативный и с кириллицей.
 */
export const display = Oswald({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-display",
});

/**
 * Терминальный слой: служебные метки, показания, коды.
 *
 * У DedSec ASCII и моноширинный набор — часть языка, а не украшение:
 * они отделяют «машинное» от «сказанного человеком».
 */
export const mono = JetBrains_Mono({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-mono-brand",
});

export const text = Onest({
  subsets: ["cyrillic", "latin"],
  display: "swap",
  variable: "--font-text",
});
